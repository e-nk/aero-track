// Synthetic fixture recording for the P1 detectors (SPEC 8: mode "fixture", fake callsigns).
// Real data from Sydney rarely shows holding, rapid descents or emergency codes on demand.
// Usage: pnpm --filter web fixture:recording
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import type { RecordingFile, RecordingMeta, RecordingPoint } from "@aerotrack/shared";

const OUT = join(import.meta.dirname, "..", "public", "recordings");
const T0 = 1_792_242_000; // 17 Oct 2026, 11:00 pm Sydney (arbitrary: not a real event)
const DT = 10; // seconds between reports, like the live poll
const DURATION = 600;

interface Leg {
  sec: number;
  turnDegPerSec?: number;
  climbFpm?: number;
}

/** Dead-reckoned synthetic track: start state plus legs. */
function fly(start: { lat: number; lon: number; altFt: number; track: number; gsKt: number }, legs: Leg[], squawk: string): RecordingPoint[] {
  let { lat, lon, altFt, track } = start;
  let t = T0;
  const pts: RecordingPoint[] = [[t, lat, lon, altFt, start.gsKt, track, 0, false, squawk]];
  for (const leg of legs) {
    for (let s = 0; s < leg.sec; s += DT) {
      t += DT;
      track = (track + (leg.turnDegPerSec ?? 0) * DT + 360) % 360;
      const nm = (start.gsKt * DT) / 3600;
      lat += (nm * Math.cos((track * Math.PI) / 180)) / 60;
      lon += (nm * Math.sin((track * Math.PI) / 180)) / (60 * Math.cos((lat * Math.PI) / 180));
      altFt += ((leg.climbFpm ?? 0) * DT) / 60;
      pts.push([t, +lat.toFixed(6), +lon.toFixed(6), Math.round(altFt / 25) * 25, start.gsKt, +track.toFixed(1), leg.climbFpm ?? 0, false, squawk]);
    }
  }
  return pts.filter((p) => p[0] <= T0 + DURATION);
}

// Racetrack hold: 60 s straight, 180° turn at 3°/s, 60 s straight, 180° turn... (a standard holding pattern shape)
const hold: Leg[] = Array.from({ length: 3 }, () => [{ sec: 60 }, { sec: 60, turnDegPerSec: 3 }, { sec: 60 }, { sec: 60, turnDegPerSec: 3 }]).flat();

const rec: RecordingFile = {
  id: "fixture-p1-detectors",
  title: "Synthetic test case: holding pattern, rapid descent and emergency code",
  mode: "fixture",
  source: "AeroTrack synthetic fixture (generated by apps/web/scripts/make-fixture-recording.ts)",
  attribution: "Synthetic data · not a real aircraft",
  capturedFrom: T0,
  capturedTo: T0 + DURATION,
  bbox: [150.9, -34.2, 151.6, -33.5],
  reportedCause: null,
  aircraft: [
    { hex: "~f00001", callsign: "TEST01", registration: null, typeCode: "B738", category: "A3", points: fly({ lat: -33.62, lon: 151.3, altFt: 7000, track: 200, gsKt: 210 }, hold, "1000") },
    {
      hex: "~f00002",
      callsign: "TEST02",
      registration: null,
      typeCode: "A320",
      category: "A3",
      points: fly({ lat: -34.15, lon: 151.0, altFt: 30000, track: 20, gsKt: 420 }, [{ sec: 120 }, { sec: 60, climbFpm: -6000 }, { sec: 420, climbFpm: -1500 }], "1000"),
    },
    {
      hex: "~f00003",
      callsign: "TEST03",
      registration: null,
      typeCode: "DH8D",
      category: "A2",
      points: fly({ lat: -33.75, lon: 150.95, altFt: 9000, track: 90, gsKt: 240 }, [{ sec: 600 }], "7700"),
    },
  ],
};

writeFileSync(join(OUT, `${rec.id}.json`), JSON.stringify(rec));
const indexPath = join(OUT, "index.json");
const index: RecordingMeta[] = JSON.parse(readFileSync(indexPath, "utf8"));
const { aircraft, ...meta } = rec;
const next = [...index.filter((m) => m.id !== rec.id), { ...meta, aircraftCount: aircraft.length }].sort(
  (a, b) => (a.mode === "fixture" ? 1 : 0) - (b.mode === "fixture" ? 1 : 0) || b.capturedFrom - a.capturedFrom,
);
writeFileSync(indexPath, `${JSON.stringify(next, null, 2)}\n`);
console.log(`Wrote ${rec.id}.json (${aircraft.reduce((n, a) => n + a.points.length, 0)} points) and updated index.json`);
